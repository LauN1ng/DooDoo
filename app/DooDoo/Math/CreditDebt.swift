import Foundation

/// 信用 / 借款账户的欠款口径（2026-11-13 定案，**取代 `CardDebt`**）。
///
/// ## 只有一条规则
///
/// ```
/// 欠款 = max(0, −余额)
/// ```
///
/// 三类账户在「欠多少钱」这件事上完全一致：
/// - 储蓄 / 现金：余额为正 = 我的钱
/// - 信用 / 借款：余额为负 = 欠的钱
///
/// **额度只作分母，账单只答「本月要还」，分期计划只答「何时还完」——三者都不产生金额。**
/// 这是「统一口径」的全部含义。判据：如果还需要一个 `CardDebt` 来推导欠款，就说明没统一。
///
/// ## 为什么废掉「余额 + 账期」相加
///
/// 旧口径（`CardDebt`）把债拆在两个账本上：流水驱动的余额，以及「未还账单 + 未被账单覆盖的分期」。
/// 两个账本从不核对，于是出现两种相反方向的错：
///
/// | 情形 | 旧口径的表现 |
/// |---|---|
/// | 余额被还款流水推成 0 或正数 | `max(0,·)` 把余额项丢掉 →「记一笔消费，我欠一分不动」 |
/// | 同一笔债既有流水又有分期 | 两边都算 → 欠款翻倍（如 1,440.39 显示成 2,880.78） |
///
/// 新口径把分期债**一次性入账**进余额（见 `InstallmentService.insert` 的 `createdFromEntry` 分支），
/// 此后余额就是唯一真相，不需要第二套派生。
///
/// ## 一条不能省的配套
///
/// 债务进余额不只靠流水。`InstallmentService` 建计划时要按 `remainingDue` 入账一次；
/// 银行加进「本期应还」的利息与违约金，也要进余额——否则用户按账单还完之后，
/// 余额会变成正数，界面显示一个根本不存在的「溢缴」。
enum CreditDebt {
    /// 单张负债卡的欠款（正数，单位元）。
    ///
    /// 余额为正时返回 0：溢缴就是溢缴，不能算成负欠款去抵别的卡。
    static func owe(balance: Decimal) -> Decimal {
        balance < 0 ? -balance : 0
    }

    /// 多张负债卡的合计（正数，单位元）。
    ///
    /// **逐卡取 max 后求和**，不能先求和再取正——那样一张卡的溢缴会把另一张卡的欠款抵掉，
    /// 旧的 `NetWorth.owe` 就是这么错的。
    static func owe(balances: [Decimal]) -> Decimal {
        balances.reduce(Decimal.zero) { $0 + owe(balance: $1) }
    }
}
