const fs = require('fs');
await page.setViewportSize({ width: 880, height: 1020 });
await page.goto('file:///D:/Work/WorkBuddy_File/account/design/current/slot-and-stack.html', { waitUntil: 'domcontentloaded', timeout: 20000 });
